#!/usr/bin/env bash
# Managed-By: disk-cleanup-setup.sh
# Rootless, threshold-triggered Rust/Podman cleanup for a systemd user timer.
# CAUTION: Podman pruning deletes unused resources and a reset deletes ALL
# rootless containers, images, networks and volumes for this user.
set -Eeuo pipefail

APP=disk-cleanup
SERVICE=${APP}.service
TIMER=${APP}.timer
BIN_DIR=${HOME}/.local/bin
INSTALLED_SCRIPT=${BIN_DIR}/disk-cleanup-setup.sh
UNIT_DIR=${HOME}/.config/systemd/user
CONFIG_DIR=${HOME}/.config/disk-cleanup
CONFIG_FILE=${CONFIG_DIR}/config
STATE_DIR=${XDG_STATE_HOME:-${HOME}/.local/state}/disk-cleanup
RESET_STAMP=${STATE_DIR}/last-reset-attempt
LOCK_DIR=${XDG_RUNTIME_DIR:-${HOME}/.cache}/disk-cleanup
LOCK_FILE=${LOCK_DIR}/cleanup.lock

ROOT_DIR=${HOME}/Dev/Github/yduchesne
THRESHOLD_PERCENT=60
AGE_DAYS=2
RESET_COOLDOWN_HOURS=24
ACTION=
DRY_RUN=0
SIMULATE_TRIGGER=0

log() {
    local level=$1; shift
    printf '%s [%s] %s\n' "$(date --iso-8601=seconds)" "$level" "$*"
}
die() { log ERROR "$*" >&2; exit 1; }
usage() {
    cat <<'USAGE'
Usage: disk-cleanup-setup.sh ACTION [OPTIONS]

Actions:
  --setup       Install/configure and start the 15-minute systemd user timer
  --teardown    Disable timer, remove generated units/config/installed copy
  --run         Perform one threshold-checked cleanup (used by the service)
  --status      Show timer status and current configuration

Options for --setup and --run:
  --root DIR                 Rust project search root (default: ~/Dev/Github/yduchesne)
  --threshold-percent N      Trigger at filesystem use >= N percent (default: 60)
  --age-days N               Require target tree inactivity >= N days (default: 2)
  --reset-cooldown-hours N   Minimum time between Podman reset attempts (default: 24)

Options only for --run:
  --dry-run                  Log planned actions without deleting anything
  --simulate-trigger         Only with --dry-run; preview cleanup even below threshold

Logs: journalctl --user -u disk-cleanup.service -n 150 --no-pager
NOTE: This affects only current user's rootless Podman storage, NOT rootful Podman.
WARNING: Podman reset fallback destroys all of this user's Podman storage.
USAGE
}

# User-owned configuration, generated by --setup only. No global/root config.
if [[ -f "$CONFIG_FILE" ]]; then
    [[ -O "$CONFIG_FILE" && ! -L "$CONFIG_FILE" ]] || die "Unsafe config file: $CONFIG_FILE"
    # shellcheck disable=SC1090
    source "$CONFIG_FILE"
fi

while (($#)); do
    case "$1" in
        --setup|--teardown|--run|--status)
            [[ -z "$ACTION" ]] || die 'Specify exactly one action'
            ACTION=$1; shift ;;
        --root|--threshold-percent|--age-days|--reset-cooldown-hours)
            (($# >= 2)) || die "Missing value for $1"
            case "$1" in
                --root) ROOT_DIR=$2 ;;
                --threshold-percent) THRESHOLD_PERCENT=$2 ;;
                --age-days) AGE_DAYS=$2 ;;
                --reset-cooldown-hours) RESET_COOLDOWN_HOURS=$2 ;;
            esac
            shift 2 ;;
        --dry-run) DRY_RUN=1; shift ;;
        --simulate-trigger) SIMULATE_TRIGGER=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) die "Unknown option: $1" ;;
    esac
done
[[ -n "$ACTION" ]] || { usage; exit 2; }

validate_options() {
    [[ "$THRESHOLD_PERCENT" =~ ^[0-9]+$ ]] && ((THRESHOLD_PERCENT >= 1 && THRESHOLD_PERCENT <= 99)) || die 'threshold must be 1..99'
    [[ "$AGE_DAYS" =~ ^[0-9]+$ ]] && ((AGE_DAYS >= 1 && AGE_DAYS <= 365)) || die 'age-days must be 1..365'
    [[ "$RESET_COOLDOWN_HOURS" =~ ^[0-9]+$ ]] && ((RESET_COOLDOWN_HOURS >= 1 && RESET_COOLDOWN_HOURS <= 8760)) || die 'reset-cooldown-hours must be 1..8760'
    [[ "$ROOT_DIR" = /* && "$ROOT_DIR" != / && "$ROOT_DIR" != "$HOME" ]] || die 'root must be an absolute path below a specific directory (not HOME or /)'
    [[ "$ROOT_DIR" != *$'\n'* && "$ROOT_DIR" != *$'\r'* ]] || die 'root contains newline'
}
validate_options

if (( EUID == 0 )); then
    die 'Refusing to manage rootful Podman: run as an unprivileged login user (no sudo)'
fi

if [[ "$ACTION" != --run && ( "$DRY_RUN" -eq 1 || "$SIMULATE_TRIGGER" -eq 1 ) ]]; then
    die '--dry-run and --simulate-trigger are only valid with --run'
fi
if (( SIMULATE_TRIGGER && ! DRY_RUN )); then
    die '--simulate-trigger requires --dry-run (never force destructive cleanup)'
fi

# A Pi invocation can have process name "pi" or a Node/Bun runtime executing
# the Pi CLI. Scan *this user's* /proc entries rather than matching unrelated
# command lines or this script's own strings. False positives skip cleanup.
pi_running() {
    local proc comm arg base pid
    local -a argv=()
    [[ -d /proc ]] || { log WARN '/proc unavailable; skip cleanup'; return 0; }
    for proc in /proc/[0-9]*; do
        [[ -d "$proc" && -O "$proc" ]] || continue
        pid=${proc##*/}
        [[ "$pid" != "$$" && "$pid" != "$PPID" ]] || continue
        comm=
        IFS= read -r comm < "$proc/comm" 2>/dev/null || continue
        if [[ "$comm" == pi ]]; then
            log WARN "Pi Agent detected (PID $pid, comm=pi); cleanup skipped"
            return 0
        fi
        argv=()
        mapfile -d '' -t argv < "$proc/cmdline" 2>/dev/null || continue
        ((${#argv[@]})) || continue
        base=${argv[0]##*/}
        if [[ "$base" == pi || "$base" == pi.exe ]]; then
            log WARN "Pi Agent detected (PID $pid, executable=$base); cleanup skipped"
            return 0
        fi
        # Handle installed npm/global CLI or node/bun /path/.../cli.js.
        if [[ "$base" == node || "$base" == bun || "$base" == node.exe || "$base" == bun.exe ]]; then
            for arg in "${argv[@]:1}"; do
                case "$arg" in
                    pi|*/bin/pi|*/pi-coding-agent/dist/cli.js|*/pi-coding-agent/*/cli.js|*/pi/dist/cli.js)
                        log WARN "Pi Agent detected (PID $pid, runtime=$base); cleanup skipped"
                        return 0 ;;
                esac
            done
        fi
    done
    return 1
}

check_pi_or_skip() {
    if pi_running; then
        return 1
    fi
    return 0
}

# df -P reads the filesystem *containing* the supplied path. GNU/Linux / WSL2.
fs_percent() {
    local output value
    output=$(df -Pk -- "$1" 2>&1) || { log ERROR "df failed for $1: $output"; return 1; }
    value=$(printf '%s\n' "$output" | awk 'END { gsub(/%/, "", $5); print $5 }')
    [[ "$value" =~ ^[0-9]+$ && "$value" -le 100 ]] || { log ERROR "Invalid df output for $1"; return 1; }
    printf '%s\n' "$value"
}

# Re-check active Pi immediately before each destructive step. This is a
# best-effort concurrency guard; it cannot make deletion atomic with launch.
check_before_destructive_step() {
    if ! check_pi_or_skip; then
        log WARN 'Cleanup stopped: Pi Agent started while cleanup was running'
        return 1
    fi
    return 0
}

# Logs command output to stdout/stderr (systemd journal), retains exit status.
podman_cmd() {
    local rc
    log INFO "Executing: podman $*"
    if timeout --signal=TERM --kill-after=10s 180s podman "$@" 2>&1 | sed -u 's/^/[podman] /'; then
        log INFO "Completed: podman $*"
        return 0
    else
        rc=$?
        log ERROR "Failed (exit $rc): podman $*"
        return "$rc"
    fi
}

reset_allowed() {
    local now previous
    mkdir -p -m 700 -- "$STATE_DIR" || { log ERROR 'Cannot create reset cooldown state directory'; return 1; }
    now=$(date +%s)
    if [[ -e "$RESET_STAMP" ]]; then
        [[ -O "$RESET_STAMP" && ! -L "$RESET_STAMP" ]] || { log ERROR 'Unsafe reset cooldown stamp'; return 1; }
        IFS= read -r previous < "$RESET_STAMP" || true
        [[ "$previous" =~ ^[0-9]+$ ]] || { log ERROR 'Invalid reset timestamp; refusing reset'; return 1; }
        if (( now < previous + RESET_COOLDOWN_HOURS * 3600 )); then
            log WARN "Podman reset blocked by ${RESET_COOLDOWN_HOURS}h cooldown (previous attempt $(date -d "@$previous" --iso-8601=seconds))"
            return 1
        fi
    fi
    return 0
}

record_reset_attempt() {
    local tmp
    tmp=$(mktemp "$STATE_DIR/.last-reset.XXXXXXXX") || return 1
    printf '%s\n' "$(date +%s)" > "$tmp" && chmod 600 "$tmp" && mv -f -- "$tmp" "$RESET_STAMP"
}

purge_podman() {
    local rc=0 running_status=0 running_output
    if ! command -v podman >/dev/null 2>&1; then
        log INFO 'Podman is not installed; Podman cleanup not applicable'
        return 0
    fi
    if (( DRY_RUN )); then
        log INFO '[DRY-RUN] Would run podman system prune --all --volumes --force; then granular prunes if it fails; reset only if those fail and safety checks pass'
        return 0
    fi
    check_before_destructive_step || return 0
    log WARN 'Podman purge removes ALL unused resources, including unused volumes; existing named data may be lost'
    if podman_cmd system prune --all --volumes --force; then
        log INFO 'Podman system prune succeeded; reset not needed'
        return 0
    fi
    log WARN 'Podman system prune failed; trying separate less-destructive prunes'
    for kind in container pod image network volume; do
        check_before_destructive_step || return 0
        case "$kind" in
            container) podman_cmd container prune --force || rc=1 ;;
            pod)       podman_cmd pod prune --force || rc=1 ;;
            image)     podman_cmd image prune --all --force || rc=1 ;;
            network)   podman_cmd network prune --force || rc=1 ;;
            volume)    podman_cmd volume prune --all --force || rc=1 ;;
        esac
    done
    if (( rc == 0 )); then
        log INFO 'All granular prunes succeeded; reset not needed'
        return 0
    fi
    log ERROR 'One or more granular prunes failed; evaluating last-resort Podman reset'
    check_before_destructive_step || return 0
    reset_allowed || return 1
    # Fail closed if Podman cannot establish whether containers are running.
    running_output=$(timeout --signal=TERM --kill-after=5s 20s podman ps --quiet 2>&1) || running_status=$?
    if (( running_status != 0 )); then
        log ERROR "Refusing reset: cannot verify whether containers are running (exit $running_status): $running_output"
        return 1
    fi
    if [[ -n "$running_output" ]]; then
        log WARN 'Refusing reset: rootless Podman currently has running containers'
        return 1
    fi
    check_before_destructive_step || return 0
    record_reset_attempt || { log ERROR 'Cannot record reset cooldown; refusing reset'; return 1; }
    log WARN 'LAST RESORT: podman system reset --force will REMOVE ALL user-owned containers, images, networks, build cache, and volumes'
    if podman_cmd system reset --force; then
        log INFO 'Podman reset completed'
        return 0
    fi
    log ERROR 'Podman reset also failed; manual inspection required'
    return 1
}

# Reject a target which is a mounted filesystem root, and let GNU rm stop at
# nested filesystem boundaries. Do not follow symlinks or remove project roots.
cleanup_rust_targets() {
    local scan_root=$1 dir candidate recent count=0 removed=0 skipped=0
    if [[ ! -d "$scan_root" ]]; then
        log WARN "Rust search root does not exist: $scan_root; skipping Rust cleanup"
        return 0
    fi
    scan_root=$(realpath -e -- "$scan_root") || { log ERROR 'Cannot canonicalize search root'; return 1; }
    [[ "$scan_root" != / && "$scan_root" != "$HOME" ]] || { log ERROR 'Unsafe canonical search root'; return 1; }
    log INFO "Scanning for Rust target directories under $scan_root (inactivity >= ${AGE_DAYS} days)"
    # Process substitution would hide find failures; use a temporary NUL file.
    local manifest
    manifest=$(mktemp "${LOCK_DIR}/targets.XXXXXXXX") || return 1
    if ! find -P "$scan_root" -xdev -type d -name target -prune -print0 > "$manifest"; then
        rm -f -- "$manifest"
        log ERROR 'Rust target discovery failed; no targets were deleted'
        return 1
    fi
    while IFS= read -r -d '' dir; do
        ((count+=1))
        [[ -d "$dir" && ! -L "$dir" ]] || { ((skipped+=1)); continue; }
        candidate=$(realpath -e -- "$dir") || { ((skipped+=1)); log WARN "Cannot canonicalize $dir"; continue; }
        case "$candidate" in
            "$scan_root"/target|"$scan_root"/*/target) ;;
            *) ((skipped+=1)); log WARN "Unsafe target outside expected tree: $candidate"; continue ;;
        esac
        if mountpoint -q -- "$candidate"; then
            ((skipped+=1)); log WARN "Skipping mounted target: $candidate"; continue
        fi
        # Do not recursively delete a tree with nested mounts, even when
        # their backing device ID matches the parent filesystem (bind mounts).
        local mounts mount_path nested=0
        if ! mounts=$(findmnt -rn --raw -o TARGET); then
            ((skipped+=1)); log WARN "Cannot inspect mount table; skipping: $candidate"; continue
        fi
        while IFS= read -r mount_path; do
            case "$mount_path" in
                "$candidate"|"$candidate"/*) nested=1; break ;;
            esac
        done <<< "$mounts"
        if (( nested )); then
            ((skipped+=1)); log WARN "Skipping target containing a mounted filesystem: $candidate"; continue
        fi
        # Inactivity is determined by *every* file/dir inside the tree, not
        # merely the target directory's own mtime (which misses rebuilds).
        if ! recent=$(find -P "$candidate" -xdev -mmin "-$((AGE_DAYS * 1440))" -print -quit); then
            ((skipped+=1)); log WARN "Cannot inspect target contents; skipping: $candidate"; continue
        fi
        if [[ -n "$recent" ]]; then
            ((skipped+=1)); log INFO "Keeping active/recent target: $candidate"
            continue
        fi
        check_before_destructive_step || { rm -f -- "$manifest"; return 0; }
        if (( DRY_RUN )); then
            log INFO "[DRY-RUN] Would delete stale Rust target: $candidate"
        elif rm --one-file-system -rf -- "$candidate"; then
            log INFO "Deleted stale Rust target: $candidate"
            ((removed+=1))
        else
            ((skipped+=1)); log ERROR "Could not remove Rust target: $candidate"
        fi
    done < "$manifest"
    rm -f -- "$manifest"
    log INFO "Rust scan completed: found=$count deleted=$removed kept_or_failed=$skipped dry_run=$DRY_RUN"
}

run_cleanup() {
    local home_used root_used after_used triggered=0 failed=0
    command -v flock >/dev/null || die 'flock is required (util-linux)'
    command -v mountpoint >/dev/null || die 'mountpoint is required (util-linux)'
    command -v findmnt >/dev/null || die 'findmnt is required (util-linux)'
    command -v realpath >/dev/null || die 'realpath is required (coreutils)'
    command -v timeout >/dev/null || die 'timeout is required (coreutils)'
    mkdir -p -m 700 -- "$LOCK_DIR" || die "Cannot create lock directory: $LOCK_DIR"
    [[ -O "$LOCK_DIR" && ! -L "$LOCK_DIR" ]] || die 'Unsafe cleanup lock directory'
    exec 9> "$LOCK_FILE"
    if ! flock -n 9; then
        log INFO 'Another cleanup run is active; skipping overlapping invocation'
        return 0
    fi
    # This MUST be the first operational check, before even asking Podman.
    if ! check_pi_or_skip; then return 0; fi
    home_used=$(fs_percent "$HOME") || return 1
    log INFO "Disk usage: home filesystem ${home_used}% (trigger >= ${THRESHOLD_PERCENT}%)"
    ((home_used >= THRESHOLD_PERCENT)) && triggered=1
    if [[ -d "$ROOT_DIR" ]]; then
        root_used=$(fs_percent "$ROOT_DIR") || return 1
        log INFO "Disk usage: Rust search-root filesystem ${root_used}%"
        ((root_used >= THRESHOLD_PERCENT)) && triggered=1
    fi
    # If Podman uses a different filesystem, check its rootless graphroot too.
    if command -v podman >/dev/null 2>&1; then
        local store= store_rc=0
        store=$(timeout --signal=TERM --kill-after=5s 20s podman info --format '{{.Store.GraphRoot}}' 2>/dev/null) || store_rc=$?
        if (( store_rc == 0 )) && [[ -d "$store" && "$store" = /* ]]; then
            root_used=$(fs_percent "$store") || return 1
            log INFO "Disk usage: rootless Podman storage filesystem ${root_used}%"
            ((root_used >= THRESHOLD_PERCENT)) && triggered=1
        else
            log WARN 'Podman storage usage unavailable; continuing with known filesystem(s)'
        fi
    fi
    if (( SIMULATE_TRIGGER )); then
        log WARN '[DRY-RUN] Simulating threshold exceeded (no deletions)'
        triggered=1
    fi
    if (( triggered == 0 )); then
        log INFO 'Below disk threshold on all monitored filesystems; no cleanup performed'
        return 0
    fi
    log WARN "Disk threshold reached; beginning Rust/Podman cleanup (dry_run=$DRY_RUN)"
    cleanup_rust_targets "$ROOT_DIR" || { log ERROR 'Rust cleanup failed; continuing to Podman cleanup'; failed=1; }
    check_before_destructive_step || return 0
    purge_podman || { log ERROR 'Podman cleanup incomplete; see prior errors'; failed=1; }
    after_used=$(fs_percent "$HOME") || return 1
    log INFO "Cleanup finished: home filesystem now ${after_used}% used (threshold ${THRESHOLD_PERCENT}%) errors=$failed"
    return "$failed"
}

systemd_ok() {
    command -v systemctl >/dev/null || die 'systemctl is unavailable; this Linux/WSL2 guest needs systemd enabled'
    systemctl --user show-environment >/dev/null 2>&1 || die 'systemd user manager is unavailable; enable systemd and a user session first'
}

setup() {
    systemd_ok
    local script src
    src=$(realpath -e -- "${BASH_SOURCE[0]}") || die 'Cannot locate this script'
    if [[ -L "$INSTALLED_SCRIPT" ]]; then die 'Refusing symlinked installed-script destination'; fi
    if [[ -e "$INSTALLED_SCRIPT" && ! -f "$INSTALLED_SCRIPT" ]]; then die 'Installed script destination is not a regular file'; fi
    if [[ -e "$INSTALLED_SCRIPT" && ! -L "$INSTALLED_SCRIPT" ]] && ! grep -q '^# Managed-By: disk-cleanup-setup.sh$' "$INSTALLED_SCRIPT"; then
        die 'Refusing to overwrite unmanaged script destination'
    fi
    local unit
    for unit in "$UNIT_DIR/$SERVICE" "$UNIT_DIR/$TIMER"; do
        [[ ! -L "$unit" ]] || die "Refusing symlinked unit: $unit"
        if [[ -e "$unit" ]] && ! grep -q '^# Managed-By: disk-cleanup-setup.sh$' "$unit"; then
            die "Refusing to overwrite unmanaged systemd unit: $unit"
        fi
    done
    mkdir -p -- "$BIN_DIR" "$UNIT_DIR" "$CONFIG_DIR"
    chmod 700 "$CONFIG_DIR"
    if [[ "$src" != "$INSTALLED_SCRIPT" ]]; then install -m 0755 -- "$src" "$INSTALLED_SCRIPT"; fi
    # Configuration persists across runs; printf %q correctly escapes spaces.
    local temp
    temp=$(mktemp "$CONFIG_DIR/.config.XXXXXXXX") || die 'Cannot create config file'
    {
        printf '# Managed-By: disk-cleanup-setup.sh\n'
        printf 'ROOT_DIR=%q\n' "$ROOT_DIR"
        printf 'THRESHOLD_PERCENT=%q\n' "$THRESHOLD_PERCENT"
        printf 'AGE_DAYS=%q\n' "$AGE_DAYS"
        printf 'RESET_COOLDOWN_HOURS=%q\n' "$RESET_COOLDOWN_HOURS"
    } > "$temp"
    chmod 600 "$temp"
    mv -f -- "$temp" "$CONFIG_FILE"
    # Escape unit-specifier '%' to avoid expansion inside ExecStart.
    script=${INSTALLED_SCRIPT//%/%%}
    [[ "$script" != *$'\n'* && "$script" != *'"'* && "$script" != *'\\'* ]] || die 'Unsupported characters in install path'
    cat > "$UNIT_DIR/$SERVICE" <<UNIT
# Managed-By: disk-cleanup-setup.sh
[Unit]
Description=Threshold-triggered Rust target and rootless Podman cleanup
Documentation=man:systemd.service(5)

[Service]
Type=oneshot
ExecStart=/usr/bin/env bash "${script}" --run
TimeoutStartSec=30min
StandardOutput=journal
StandardError=journal
UNIT
    cat > "$UNIT_DIR/$TIMER" <<UNIT
# Managed-By: disk-cleanup-setup.sh
[Unit]
Description=Check disk usage every 15 minutes and clean stale Rust/Podman data

[Timer]
OnCalendar=*:0/15
AccuracySec=1min
Persistent=true
Unit=$SERVICE

[Install]
WantedBy=timers.target
UNIT
    systemctl --user daemon-reload
    systemctl --user enable --now "$TIMER"
    log INFO "Installed $TIMER (every 15 minutes), root=$ROOT_DIR, threshold=${THRESHOLD_PERCENT}%, inactivity=${AGE_DAYS} days"
    log INFO "Logs: journalctl --user -u $SERVICE -n 150 --no-pager"
}

teardown() {
    systemd_ok
    local unit
    for unit in "$UNIT_DIR/$SERVICE" "$UNIT_DIR/$TIMER"; do
        [[ ! -L "$unit" ]] || die "Refusing symlinked unit: $unit"
        if [[ -e "$unit" ]] && ! grep -q '^# Managed-By: disk-cleanup-setup.sh$' "$unit"; then
            die "Refusing to remove unmanaged unit: $unit"
        fi
    done
    systemctl --user disable --now "$TIMER" >/dev/null 2>&1 || log WARN 'Timer already disabled/stopped or could not be stopped'
    systemctl --user stop "$SERVICE" >/dev/null 2>&1 || true
    rm -f -- "$UNIT_DIR/$SERVICE" "$UNIT_DIR/$TIMER"
    if [[ -f "$INSTALLED_SCRIPT" && ! -L "$INSTALLED_SCRIPT" ]] && grep -q '^# Managed-By: disk-cleanup-setup.sh$' "$INSTALLED_SCRIPT"; then
        rm -f -- "$INSTALLED_SCRIPT"
    fi
    if [[ -f "$CONFIG_FILE" && ! -L "$CONFIG_FILE" ]] && grep -q '^# Managed-By: disk-cleanup-setup.sh$' "$CONFIG_FILE"; then
        rm -f -- "$CONFIG_FILE"
    fi
    systemctl --user daemon-reload
    log INFO "Teardown complete: removed $SERVICE, $TIMER, and managed config/install copy. Reset cooldown/logs retained."
}

case "$ACTION" in
    --setup) setup ;;
    --teardown) teardown ;;
    --run) run_cleanup ;;
    --status)
        log INFO "Configured root=$ROOT_DIR threshold=${THRESHOLD_PERCENT}% age=${AGE_DAYS}d reset_cooldown=${RESET_COOLDOWN_HOURS}h"
        if command -v systemctl >/dev/null 2>&1; then
            systemctl --user status "$TIMER" --no-pager || true
            systemctl --user list-timers "$TIMER" --all --no-pager || true
        fi ;;
esac
